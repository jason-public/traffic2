export function getKnowledgeBaseReply(promptText: string): string {
  const p = promptText.toLowerCase().trim();

  // 1. 어르신 교통비 (만 65세 이상 / G-PASS)
  if (p.includes('어르신') || p.includes('노인') || p.includes('65세') || p.includes('g-pass') || p.includes('gpass') || p.includes('지패스')) {
    return `**[남양주시 어르신 대중교통비 지원 안내 (G-PASS)]**

• **지원 대상**: 만 65세 이상 남양주시 주민등록 거주 어르신
• **지원 금액**: 연 최대 12만원 (분기별 최대 3만원)
• **지급 방식**: 분기별 대중교통 실사용 실적 확인 후 농협 지정 계좌로 현금 환급
• **신청 방법**:
  1. 관내 농협(농협은행, 지역 농·축협 등) 방문 신청
  2. G-PASS 어르신 우대용 교통카드 발급 및 계좌 연결
• **재원 및 규모**: 시비 100% (2026년 기준 예산 약 51.2억원 집행중)
• **문의처**: 남양주시 대중교통과 또는 관내 농협 지점`;
  }

  // 2. K-패스 (만 19세 이상)
  if (p.includes('k패스') || p.includes('k-패스') || p.includes('kpass') || p.includes('케이패스')) {
    return `**[K-패스(K-PASS) 대중교통비 지원 안내]**

• **지원 대상**: 만 19세 이상 남양주시민 및 전국 주민
• **지원 조건**: 월 15회 이상 대중교통(버스, 지하철, GTX 등) 이용 시
• **환급 비율**:
  - **일반**: 20% 환급
  - **청년(만 19~34세) / 어르신**: 30% 환급
  - **저소득층**: 53.3% 환급 (월 평균 환급액 약 44,655원)
• **적용 수단**: 시내·마을버스, 광역버스, M버스, 지하철, 신분당선, GTX (고속·시외버스 제외)
• **신청 방법**:
  1. 협약 카드사(신한, KB국민, 삼성, 현대, 하나, 우리, NH농협 등)에서 K-패스 카드 발급
  2. K-패스 공식 앱 또는 누리집(korea-pass.kr) 회원가입 및 카드 등록
• **문의처**: K-패스 고객센터 (1522-4114)`;
  }

  // 3. 어린이 · 청소년 (만 6세 ~ 18세)
  if (p.includes('청소년') || p.includes('어린이') || p.includes('학생') || p.includes('6세') || p.includes('18세')) {
    return `**[어린이·청소년 대중교통비 지원 안내]**

• **지원 대상**: 만 6세 ~ 만 18세 어린이 및 청소년 (남양주시 거주자)
• **지원 금액**: 연 최대 24만원 (분기별 최대 6만원)
• **지급 방식**: 남양주사랑상품권 (지역화폐)으로 환급 지급
• **신청 방법**: 경기도 어린이·청소년 교통비 지원 포털(pbup.kr)에서 온라인 신청
• **필요 항목**: 본인 또는 부모 명의 회원가입, 사용 교통카드 등록 및 지역화폐 등록
• **문의처**: 경기도 교통비 지원 콜센터 (1577-8459)`;
  }

  // 4. M버스 (광역급행버스)
  if (p.includes('m버스') || p.includes('광역급행') || p.includes('잠실')) {
    return `**[남양주시 M버스(광역급행) 운행 현황]**

남양주시는 총 **5개 노선 49대**의 M버스를 운행 중이며, 전 노선 대광위 준공영제가 적용됩니다:

1. **M2341**: 화도월산부영 ↔ 잠실광역환승센터 (6대)
2. **M2352**: 평내동 ↔ 잠실광역환승센터 (10대)
3. **M2353**: 다산진건지구 ↔ 잠실광역환승센터 (10대)
4. **M2316**: 화도영남아파트 ↔ 잠실광역환승센터 (10대)
5. **M2323**: 호평동 ↔ 잠실광역환승센터 (13대)

• **특징**: 출퇴근 시간대 빠른 서울(잠실) 접근성을 제공하며 승차잔여석 안내 서비스가 지원됩니다.`;
  }

  // 5. 땡큐버스 & 트롤리버스
  if (p.includes('땡큐') || p.includes('트롤리')) {
    return `**[땡큐버스 & 트롤리버스 운행 현황]**

• **땡큐버스**: 남양주시 권역간 유기적 연결을 위해 구축된 대표 브랜드 버스로, 총 **16개 노선 130대**가 운행 중입니다.
• **트롤리버스**: 유럽형 레트로 클래식 디자인을 적용한 특화 버스로, 총 **4개 노선 10대**가 운행됩니다.
  - 배치 노선: 땡큐70, 땡큐90, 땡큐58-3, 58번 노선
• **이용 안내**: 일반 시내버스 요금과 동일하며, 환승할인이 동일하게 적용됩니다.`;
  }

  // 6. 2층 버스
  if (p.includes('2층') || p.includes('이층')) {
    return `**[남양주시 2층 버스 도입 및 운행 현황]**

• **도입 대수**: 총 **7개 노선 40대** 도입 (친환경 전기 2층버스 4대, 디젤 36대)
• **실운행 수량**: 총 29대 (출퇴근 혼잡 완화 집중 투입)
• **운행 노선**: 8002번, 8012번, M2323번, M2352번, 1670번, 1001번, 1003번
• **효과**: 기존 1층 버스 대비 수송 능력이 1.5배 높아서 광역버스 입석 예방 및 안전성 향상에 크게 기여하고 있습니다.`;
  }

  // 7. 스마트 승강장
  if (p.includes('스마트') || p.includes('승강장') || p.includes('정류장') || p.includes('쉘터')) {
    return `**[남양주시 스마트 승강장 현황 및 편의시설]**

• **전체 정류장 수**: 총 1,913개소 (쉘터형 1,053, 표지판형 521, 무표지형 257, 독립형 39, 스마트 승강장 43)
• **스마트 승강장**: 관내 주요 거점 **43개소** 구축 완료
• **주요 위치**: 평내호평역(1,2,3번출구), 호평이마트, 다산선형공원, 오남역, 마석역, 사능역, 덕소역 등
• **제공 편의시설**:
  - 냉난방기 (여름철 폭염 / 겨울철 한파 차단)
  - 공기청정기 및 UV 살균 시스템
  - 버스도착안내기(BIT) 및 공공 Wi-Fi
  - 휴대폰 무선/유선 충전기, 비상벨 및 CCTV 안전 시스템`;
  }

  // 8. 택시 및 택시쉼터
  if (p.includes('택시') || p.includes('쉼터') || p.includes('고요한')) {
    return `**[남양주시 택시 및 택시쉼터 현황]**

• **택시 면허 대수**: 총 **1,291대** (개인택시 949대, 법인택시 342대 / 6개 업체)
• **종사자 수**: 1,514명
• **특화 서비스**: **고요한택시** 3대 운행 (청각장애인 운전원 전용 청각 보조 장치 탑재)
• **택시 쉼터 운영**:
  - **남부택시쉼터**: 호평동 (면적 446㎡, 개인택시조합 위탁)
  - **북부택시쉼터**: 오남읍 (면적 340.85㎡, 법인택시 위탁)
• **택시 승차대**: 총 53개소 (쉘터형 30개소, 포스트형 23개소, 태양광 7개소)`;
  }

  // 9. 수송분담률 & 통계
  if (p.includes('수송') || p.includes('분담률') || p.includes('통계') || p.includes('교통량') || p.includes('비율')) {
    return `**[남양주시 대중교통 수송분담률 통계 (2025년 기준)]**

• **총 통행량**: 일 평균 **907,382통행/일**
• **수단별 분담률**:
  1. **승용차**: 60.08% (545,128건/일)
  2. **버스**: 27.26% (247,372건/일)
  3. **철도**: 8.35% (75,771건/일)
  4. **택시**: 4.31% (39,111건/일)
• **시내 버스 노선 규모**: 총 124개 노선 730대 운행 중 (광역급행 5노선 49대, 직행좌석 23노선 180대, 일반시내 66노선 396대, 마을버스 30노선 105대)`;
  }

  // 10. 지원 정책 전반
  if (p.includes('지원') || p.includes('정책') || p.includes('교통비') || p.includes('환급')) {
    return `**[남양주시 대중교통비 지원 3대 핵심 사업]**

1. **K-패스 (만 19세 이상)**:
   - 월 15회 이상 이용 시 대중교통비 20% ~ 53% 환급 (청년/어르신 30%, 저소득 53%)
2. **어르신 교통비 지원 (만 65세 이상)**:
   - 관내 농협에서 G-PASS 카드 신청 후 연 최대 12만원(분기당 3만원) 현금 환급
3. **어린이·청소년 교통비 지원 (만 6세~18세)**:
   - 경기교통비 포털 온라인 신청 후 연 최대 24만원(분기당 6만원) 남양주사랑상품권 환급

궁금하신 특정 지원 사업의 상세 내용을 입력하시면 맞춤 안내해 드립니다!`;
  }

  return `안녕하세요! 남양주시 대중교통과 AI 정책 도우미입니다. 🚍

질문하신 내용과 관련하여 다음과 같은 남양주시 주요 대중교통 현황 및 정책을 안내해 드립니다:

• **교통비 지원 사업**: K-패스(만 19세 이상), 어르신 교통비 지원(만 65세 이상 연 12만원), 어린이·청소년 교통비(만 6~18세 연 24만원)
• **버스 운행 정보**: M버스 5개 노선(49대), 땡큐버스 16개 노선(130대), 트롤리버스 4개 노선(10대), 2층 버스 7개 노선(40대)
• **시민 편의 시설**: 관내 43개 스마트 승강장(냉난방, BIT, 공공Wi-Fi), 남부/북부 택시쉼터

원하시는 세부 질문(예: '어르신 교통비 신청 방법', 'K패스 환급 자격', 'M버스 노선')을 질문해 주시면 상세히 안내해 드리겠습니다!`;
}
